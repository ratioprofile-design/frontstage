import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.FRONTSTAGE_PLAYWRIGHT_MODULE || 'playwright-core');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = await mkdtemp(path.join(tmpdir(), 'frontstage-browser-'));
const port = 17843, address = `http://127.0.0.1:${port}`;
const server = spawn(path.join(root, '.build/debug/FrontstageServer'), ['serve', '--hostname', '127.0.0.1', '--port', String(port)], { cwd: root, env: { ...process.env, FRONTSTAGE_DATA_DIR: directory, FRONTSTAGE_ALLOW_SIGNUP: '1' }, stdio: 'ignore' });
let browser;
async function wait(check, message) { for (let i = 0; i < 100; i++) { if (await check().catch(() => false)) return; await new Promise(r => setTimeout(r, 200)); } throw Error(message); }
try {
  await wait(async () => (await fetch(address + '/health')).ok, 'Server startup');
  browser = await chromium.launch({ executablePath: process.env.FRONTSTAGE_CHROMIUM || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(address);
  const credentials = { username: 'browser_test', password: 'Only-a-local-fixture-12345' };
  await page.getByLabel('Username', { exact: true }).fill(credentials.username);
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Create Account', exact: true }).click();
  await page.waitForSelector('#projects:not([hidden])');
  page.once('dialog', dialog => dialog.accept('Browser Story'));
  await page.getByRole('button', { name: 'New Whiteboard', exact: true }).click();
  await page.waitForSelector('#workspace:not([hidden])');
  await page.locator('#add-block').click();
  await page.locator('#beat-title').fill('The Arrival');
  await page.locator('#snippet-editor').fill('The first decision.');
  await page.locator('#close-editor').click();
  await page.locator('#add-beat').click();
  await page.locator('#beat-title').fill('The Consequence');
  await page.locator('#snippet-editor').fill('தமிழ் — the second decision.');
  await page.locator('#must-cause').check();
  await page.locator('#close-editor').click();
  await page.getByText('The Arrival', { exact: true }).first().click();
  await page.locator('#cause').click();
  await page.getByText('The Consequence', { exact: true }).first().click();
  await page.locator('#resolve').click();
  await wait(async () => /^Synced/.test(await page.locator('#status').innerText()), 'Initial sync');
  const login = await fetch(address + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(credentials) }).then(r => r.json());
  const headers = { Authorization: `Bearer ${login.token}`, 'Content-Type': 'application/json' };
  const projects = await fetch(address + '/api/projects', { headers }).then(r => r.json());
  const endpoint = address + '/api/projects/' + projects[0].id;
  const first = await fetch(endpoint, { headers }).then(r => r.json());
  assert.equal(first.document.project.frontstageWhiteboard.beats.length, 2);
  assert.equal(first.document.project.frontstageWhiteboard.dependencies.length, 1);
  await page.getByText('The Consequence', { exact: true }).first().dblclick();
  await context.setOffline(true);
  await page.locator('#snippet-editor').fill('தமிழ் — edited offline.');
  await page.getByText('The Arrival', { exact: true }).first().click();
  assert.equal(await page.locator('#beat-title').inputValue(), 'The Consequence');
  const remote = structuredClone(first.document); remote.name = 'Remote project rename';
  const updated = await fetch(endpoint, { method: 'PUT', headers, body: JSON.stringify({ expectedRevision: first.revision, changeID: crypto.randomUUID(), document: remote }) });
  assert.equal(updated.status, 200);
  await context.setOffline(false);
  await page.locator('#close-editor').click();
  await page.locator('#save').click();
  await wait(async () => {
    const snapshot = await fetch(endpoint, { headers }).then(r => r.json());
    return snapshot.document.name === 'Remote project rename' && snapshot.document.project.frontstageWhiteboard.beats.some(b => b.html.includes('edited offline'));
  }, 'Offline/reconnect merge');
  const artifact = path.resolve(root, '../build'); await mkdir(artifact, { recursive: true });
  await page.screenshot({ path: path.join(artifact, 'browser-whiteboard.png') });
  await page.getByText('The Consequence', { exact: true }).first().dblclick();
  await page.screenshot({ path: path.join(artifact, 'browser-popup.png') });
  assert.deepEqual(errors, []);
  console.log('PASS: browser account, project, stacked beats, popup identity, causes, offline edits and three-way reconnect merge');
} finally {
  if (browser) await browser.close();
  server.kill('SIGTERM');
  await new Promise(resolve => server.once('exit', resolve));
  await rm(directory, { recursive: true, force: true });
}
