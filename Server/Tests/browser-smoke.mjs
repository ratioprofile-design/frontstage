import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, rm, readFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.FRONTSTAGE_PLAYWRIGHT_MODULE || 'playwright-core');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = await mkdtemp(path.join(tmpdir(), 'frontstage-browser-'));
const port = 17843, address = `http://127.0.0.1:${port}`;
const staticMode = process.env.FRONTSTAGE_STATIC_BROWSER === '1', webAddress = staticMode ? 'http://127.0.0.1:17844' : address;
const server = spawn(path.join(root, '.build/debug/FrontstageServer'), ['serve', '--hostname', '127.0.0.1', '--port', String(port)], { cwd: root, env: { ...process.env, FRONTSTAGE_DATA_DIR: directory, FRONTSTAGE_ALLOW_SIGNUP: '1', ...(staticMode ? { FRONTSTAGE_WEB_ORIGIN: webAddress } : {}) }, stdio: 'ignore' });
let staticServer;
let browser;
async function wait(check, message) { for (let i = 0; i < 100; i++) { if (await check().catch(() => false)) return; await new Promise(r => setTimeout(r, 200)); } throw Error(message); }
try {
  await wait(async () => (await fetch(address + '/health')).ok, 'Server startup');
  if (staticMode) {
    const types = { 'index.html': 'text/html', 'style.css': 'text/css', 'app.js': 'application/javascript', 'merge.js': 'application/javascript', 'config.js': 'application/javascript' };
    staticServer = createServer(async (request, response) => {
      const file = request.url === '/' ? 'index.html' : request.url.slice(1);
      if (!types[file]) { response.writeHead(404); response.end(); return; }
      try { response.setHeader('Content-Type', types[file]); response.end(await readFile(path.resolve(root, '../build/web', file))); }
      catch { response.writeHead(500); response.end('Static build missing'); }
    });
    await new Promise(resolve => staticServer.listen(17844, '127.0.0.1', resolve));
  }
  browser = await chromium.launch({ executablePath: process.env.FRONTSTAGE_CHROMIUM || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : chromium.executablePath()), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(webAddress);
  if (staticMode) await page.getByLabel('Shared server', { exact: true }).fill(address);
  const credentials = { username: 'browser_test', password: 'Only-a-local-fixture-12345' };
  await page.getByLabel('Username', { exact: true }).fill(credentials.username);
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Create Account', exact: true }).click();
  await page.waitForSelector('#projects:not([hidden])');
  page.once('dialog', dialog => dialog.accept('Browser Story'));
  await page.getByRole('button', { name: 'New Whiteboard', exact: true }).click();
  await page.waitForSelector('#workspace:not([hidden])');
  await page.locator('#add-block').click();
  await page.locator('#beat-title').fill('The Arrival');
  await page.locator('#snippet-editor').fill('The first decision.');
  await page.locator('#close-editor').click();
  await page.locator('#add-beat').click();
  await page.locator('#beat-title').fill('The Consequence');
  await page.locator('#snippet-editor').fill('தமிழ் — the second decision.');
  await page.locator('#must-cause').check();
  await page.locator('#close-editor').click();
  await page.locator('#blocks .beat-text').getByText('The Arrival', { exact: true }).click();
  await page.locator('#cause').click();
  await page.locator('#blocks .beat-text').getByText('The Consequence', { exact: true }).click();
  await page.locator('#resolve').click();
  await wait(async () => /^Synced/.test(await page.locator('#status').innerText()), 'Initial sync');
  const login = await fetch(address + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(credentials) }).then(r => r.json());
  const headers = { Authorization: `Bearer ${login.token}`, 'Content-Type': 'application/json' };
  const projects = await fetch(address + '/api/projects', { headers }).then(r => r.json());
  const endpoint = address + '/api/projects/' + projects[0].id;
  const first = await fetch(endpoint, { headers }).then(r => r.json());
  assert.equal(first.document.project.frontstageWhiteboard.beats.length, 2);
  assert.equal(first.document.project.frontstageWhiteboard.dependencies.length, 1);
  await page.locator('#blocks .beat-text').getByText('The Consequence', { exact: true }).dblclick();
  await context.setOffline(true);
  await page.locator('#snippet-editor').fill('தமிழ் — edited offline.');
  await page.locator('#blocks .beat-text').getByText('The Arrival', { exact: true }).click();
  assert.equal(await page.locator('#beat-title').inputValue(), 'The Consequence');
  const remote = structuredClone(first.document); remote.name = 'Remote project rename';
  const updated = await fetch(endpoint, { method: 'PUT', headers, body: JSON.stringify({ expectedRevision: first.revision, changeID: randomUUID(), document: remote }) });
  assert.equal(updated.status, 200);
  await context.setOffline(false);
  await page.locator('#close-editor').click();
  await page.locator('#save').click();
  await wait(async () => {
    const snapshot = await fetch(endpoint, { headers }).then(r => r.json());
    return snapshot.document.name === 'Remote project rename' && snapshot.document.project.frontstageWhiteboard.beats.some(b => b.html.includes('edited offline'));
  }, 'Offline/reconnect merge');
  const artifact = path.resolve(root, '../build'); await mkdir(artifact, { recursive: true });
  await page.screenshot({ path: path.join(artifact, `browser-${staticMode ? 'static-' : ''}whiteboard.png`) });
  await page.locator('#blocks .beat-text').getByText('The Consequence', { exact: true }).dblclick();
  await page.screenshot({ path: path.join(artifact, `browser-${staticMode ? 'static-' : ''}popup.png`) });
  const latest = await fetch(endpoint, { headers }).then(r => r.json());
  const secondDocument = structuredClone(latest.document); secondDocument.name = 'Second project';
  secondDocument.project.frontstageWhiteboard.beats.find(b => b.title === 'The Consequence').title = 'Another project beat';
  secondDocument.project.beats.forEach(scene => { scene.frontstageTextLocked = true; });
  const secondProject = await fetch(address + '/api/projects', { method: 'POST', headers, body: JSON.stringify({ document: secondDocument }) }).then(r => r.json());
  let releaseResponse, responseHeld = false;
  const responseGate = new Promise(resolve => { releaseResponse = resolve; });
  await page.route(endpoint, async route => {
    if (route.request().method() !== 'PUT') return route.continue();
    const response = await route.fetch(); responseHeld = true;
    await responseGate; await route.fulfill({ response });
  });
  await page.locator('#beat-title').fill('Old project pending title');
  await page.locator('#close-editor').click();
  await page.locator('#save').click();
  await wait(() => Promise.resolve(responseHeld), 'Delayed first-project sync response');
  await page.locator('#back').click();
  await page.locator('#project-list button').filter({ hasText: 'Second project' }).click();
  await page.locator('#blocks .beat-text').getByText('Another project beat', { exact: true }).waitFor();
  releaseResponse();
  await page.waitForTimeout(400);
  assert.equal(await page.locator('#blocks .beat-text').getByText('Another project beat', { exact: true }).count(), 1);
  assert.equal(await page.locator('#blocks .beat-text').getByText('Old project pending title', { exact: true }).count(), 0);
  await page.locator('#blocks .beat-text').getByText('Another project beat', { exact: true }).dblclick();
  assert.equal(await page.locator('#snippet-editor').getAttribute('contenteditable'), 'false');
  const unchanged = await fetch(address + '/api/projects/' + secondProject.id, { headers }).then(r => r.json());
  assert.equal(unchanged.revision, 1);
  const localContext = await browser.newContext({ viewport: { width: 1440, height: 950 }, acceptDownloads: true });
  const localPage = await localContext.newPage(), localAPIRequests = [];
  localPage.on('pageerror', error => errors.push(error.message));
  localPage.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) localAPIRequests.push(request.url()); });
  await localPage.goto(webAddress);
  await localPage.locator('#local-mode').click();
  await localPage.waitForSelector('#workspace:not([hidden])');
  await localPage.locator('#add-block').click();
  await localPage.locator('#beat-title').fill('Local story beat');
  await localPage.locator('#snippet-editor').fill('தமிழ் — stored on this device.');
  await localPage.locator('#close-editor').click();
  await localPage.locator('#save').click();
  await wait(async () => await localPage.locator('#status').innerText() === 'Saved on this device', 'Local project save');
  await localPage.reload();
  await localPage.locator('#local-mode').click();
  await localPage.getByRole('button', { name: 'Untitled Story · on this device', exact: true }).click();
  await localPage.locator('#blocks .beat-text').getByText('Local story beat', { exact: true }).dblclick();
  assert.equal(await localPage.locator('#snippet-editor').innerText(), 'தமிழ் — stored on this device.');
  await localContext.setOffline(true);
  await localPage.locator('#snippet-editor').fill('தமிழ் — local edit while offline.');
  await localPage.locator('#close-editor').click();
  await localPage.locator('#save').click();
  await wait(async () => await localPage.locator('#status').innerText() === 'Saved on this device', 'Offline local save');
  const downloadPromise = localPage.waitForEvent('download');
  await localPage.locator('#download').click();
  const download = await downloadPromise;
  const localDocument = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(localDocument.project.frontstageWhiteboard.beats[0].title, 'Local story beat');
  assert.ok(localDocument.project.beats[0].content.includes('local edit while offline'));
  await localContext.setOffline(false);
  await localPage.locator('#back').click();
  const legacy = structuredClone(localDocument.project);
  legacy.geminiApiKey = 'synthetic-unused-fixture'; legacy.vault = [{ r2SecretAccessKey: 'synthetic-unused-fixture', customField: 42 }];
  await localPage.locator('#import-project').setInputFiles({ name: 'legacy.backstage', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy)) });
  await localPage.waitForSelector('#workspace:not([hidden])');
  const importedDownloadPromise = localPage.waitForEvent('download');
  await localPage.locator('#download').click();
  const imported = JSON.parse(await readFile(await (await importedDownloadPromise).path(), 'utf8'));
  assert.equal(imported.project.geminiApiKey, undefined);
  assert.equal(imported.project.vault[0].r2SecretAccessKey, undefined);
  assert.equal(imported.project.vault[0].customField, 42);
  assert.ok(imported.project.beats[0].content.includes('local edit while offline'));
  assert.deepEqual(localAPIRequests, []);
  await localContext.close();
  assert.deepEqual(errors, []);
  console.log(`PASS (${staticMode ? 'static cross-origin' : 'same-origin'}): browser account, beats/popup/causes, offline merge, project isolation, script locks, local projects/reload/offline/export without API requests`);
} catch (error) {
  const details = String(error.stack || error).replaceAll('%', '%25').replaceAll('\r', '%0D').replaceAll('\n', '%0A');
  console.error(`::error::${details}`);
  throw error;
} finally {
  if (browser) await browser.close();
  if (staticServer) { staticServer.closeAllConnections(); await new Promise(resolve => staticServer.close(resolve)); }
  server.kill('SIGTERM');
  await new Promise(resolve => server.once('exit', resolve));
  await rm(directory, { recursive: true, force: true });
}
